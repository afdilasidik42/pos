const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
const output=fs.mkdtempSync(path.join(require('node:os').tmpdir(),'coffee-express-'));
// Use an existing local Playwright installation; no project dependency required.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
(async()=>{
  const browser=await chromium.launch({headless:true});
  const page=await browser.newPage({viewport:{width:1440,height:1050}});
  const errors=[],requests=[];
  page.on('pageerror',e=>errors.push(e.message));
  page.on('request',r=>{if(/^https?:/.test(r.url())) requests.push(r.url())});
  await page.goto(pathToFileURL(path.resolve('index.html')).href);
  await page.getByRole('button',{name:'Online Order',exact:true}).click();
  await page.screenshot({path:path.join(output,'preview-order.png')});
  const initial=await page.evaluate(()=>({cash:STATE.totalCashBank,revenue:STATE.monthlyRevenue,journals:STATE.journals.length}));
  await page.locator('#orderFloatingCart').click();
  await page.getByRole('button',{name:'Lewati pembayaran — uji coba',exact:true}).click();
  const first=await page.evaluate(()=>({order:STATE.orders[0],cash:STATE.totalCashBank,revenue:STATE.monthlyRevenue,journals:STATE.journals.length}));
  assert.equal(first.order.paymentStatus,'unpaid');
  assert.equal(first.cash,initial.cash); assert.equal(first.revenue,initial.revenue); assert.equal(first.journals,initial.journals);
  await page.getByRole('button',{name:'Lihat konfirmasi WhatsApp',exact:true}).click();
  assert.match(await page.locator('#waMessagesStream').innerText(),new RegExp(first.order.id));
  assert.match(await page.locator('#waMessagesStream').innerText(),/Belum dibayar/);
  await page.screenshot({path:path.join(output,'preview-whatsapp.png')});
  await page.getByRole('button',{name:'POS',exact:true}).click();
  await page.evaluate(()=>switchPosTab('pesanan'));
  const card=page.locator('#orderCard-'+first.order.id);
  assert.match(await card.innerText(),/Belum dibayar/);
  await card.getByRole('button',{name:'Proses Barista'}).click();
  await page.screenshot({path:path.join(output,'preview-pos.png')});
  await card.getByRole('button',{name:'Siap Saji'}).click();
  await card.getByRole('button',{name:'Selesaikan'}).click();
  assert.equal(await page.evaluate(()=>document.querySelector('#step4').classList.contains('active')),true);
  assert.equal(await page.evaluate(()=>STATE.totalCashBank),initial.cash);
  await page.evaluate(()=>{openCustomerChat();switchWaPersona('owner');switchWaPersona('customer')});
  assert.match(await page.locator('#waMessagesStream').innerText(),/Pesanan selesai/);
  await page.getByRole('button',{name:'Status Pesanan',exact:true}).click();
  await page.waitForTimeout(600);
  assert.match(await page.locator('#waMessagesStream').innerText(),/Status: Selesai/);
  await page.evaluate(()=>{appendWaMessage('out','<img src=x onerror=alert(1)>')});
  assert.equal(await page.locator('#waMessagesStream img').count(),0);
  // A second order must stay independent from the first and retain the selected outlet.
  await page.evaluate(()=>{switchDevice('order');closeOrderSubpages();toggleMobileOutlet();addProductToMobileCart(MOCK_DATA.products[1]);openOrderCheckout()});
  await page.getByRole('button',{name:'Bayar Sekarang (Simulasi QRIS)',exact:true}).click();
  const paid=await page.evaluate(()=>STATE.orders[0]);
  assert.notEqual(paid.id,first.order.id); assert.match(paid.outlet,/Dago/); assert.equal(paid.paymentStatus,'paid');
  assert.equal(await page.evaluate(()=>STATE.totalCashBank),initial.cash+paid.total);
  const count=await page.evaluate(()=>STATE.orders.length);
  await page.evaluate(()=>submitMobileOrder(true));
  assert.equal(await page.evaluate(()=>STATE.orders.length),count);
  await page.evaluate((id)=>advanceOrderStatus(id,'proses'),first.order.id);
  assert.equal(await page.evaluate(()=>document.querySelector('#step1').classList.contains('active')),true);
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>closeOrderSubpages());
  await page.screenshot({path:path.join(output,'preview-mobile.png'),fullPage:true});
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
  await page.locator('#orderProductList button').first().focus();
  await page.keyboard.press('Enter');
  assert.ok(await page.evaluate(()=>STATE.mobileCart.length>0));
  await page.locator('#orderFloatingCart').click();
  await page.getByRole('button',{name:/Kurangi /}).first().click();
  assert.equal(await page.evaluate(()=>STATE.mobileCart.length),0);
  assert.equal(await page.locator('#orderSubpageCheckout').evaluate(el=>el.classList.contains('active')),false);
  await page.getByRole('button',{name:'Lacak pesanan terakhir'}).click();
  assert.equal(await page.locator('#trackOrderNo').innerText(),'#'+paid.id);
  await page.setViewportSize({width:1024,height:768});
  await page.evaluate(()=>{switchDevice('pos');switchPosTab('kasir');openPaymentModal()});
  await page.evaluate(()=>{closeModal('paymentModal');switchPosTab('accounting')});
  await page.screenshot({path:path.join(output,'preview-accounting.png'),fullPage:true});
  assert.equal(await page.locator('#posScreenAccounting').isVisible(),true);
  // Exercise native drag/drop, including all six directions between working columns.
  await page.evaluate(()=>switchPosTab('pesanan'));
  assert.equal(await page.locator('.kanban-board > .kanban-col').count(),3);
  const beforeMoves=await page.evaluate(()=>({cash:STATE.totalCashBank,revenue:STATE.monthlyRevenue,journals:STATE.journals.length}));
  const targets={proses:'#kanbanColProses',siap:'#kanbanColSiap',selesai:'#kanbanColSelesai'};
  const movingCard=page.locator('#orderCard-'+paid.id);
  for(const destination of ['proses','siap','proses','selesai','siap','selesai','proses']) {
    await movingCard.dragTo(page.locator(targets[destination]),{targetPosition:{x:60,y:65}});
    assert.equal(await page.evaluate(id=>STATE.orders.find(o=>o.id===id).status,paid.id),destination);
    assert.equal(await movingCard.locator('..').getAttribute('id'),{proses:'colProsesCards',siap:'colSiapCards',selesai:'colSelesaiCards'}[destination]);
  }
  assert.equal(await page.evaluate(()=>document.querySelector('#step2').classList.contains('active')),true);
  assert.match(await page.evaluate(()=>STATE.customerMessages.at(-1).text),/Koreksi status/);
  const messageCount=await page.evaluate(()=>STATE.customerMessages.length);
  await movingCard.dragTo(page.locator('#kanbanColBaru'));
  assert.equal(await page.evaluate(id=>STATE.orders.find(o=>o.id===id).status,paid.id),'proses');
  // Reject intake/unknown destinations even if called outside the drag UI.
  await page.evaluate(id=>{advanceOrderStatus(id,'baru');advanceOrderStatus(id,'invalid');advanceOrderStatus(id,'proses')},paid.id);
  assert.equal(await page.evaluate(()=>STATE.customerMessages.length),messageCount);
  assert.deepEqual(await page.evaluate(()=>({cash:STATE.totalCashBank,revenue:STATE.monthlyRevenue,journals:STATE.journals.length})),beforeMoves);
  await movingCard.getByRole('combobox').selectOption('selesai');
  await movingCard.getByRole('combobox').selectOption('siap');
  assert.equal(await page.evaluate(id=>STATE.orders.find(o=>o.id===id).status,paid.id),'siap');
  // Many incoming orders stay in one horizontally scrollable row.
  await page.evaluate(()=>{
    const sample=STATE.orders[0];
    for(let i=0;i<8;i++) STATE.orders.push({...sample,id:'TEST-'+i,status:'baru'});
    renderOrdersKanban();
  });
  const queue=await page.locator('#colBaruCards').evaluate(el=>({overflow:el.scrollWidth>el.clientWidth,top:el.getBoundingClientRect().top,bottom:el.getBoundingClientRect().bottom,rows:[...el.children].map(c=>c.getBoundingClientRect().top)}));
  assert.equal(queue.overflow,true);
  assert.equal(new Set(queue.rows).size,1);
  assert.ok((await page.locator('.kanban-board').boundingBox()).y>=queue.bottom);
  await page.locator('#colBaruCards').evaluate(el=>el.scrollLeft=el.scrollWidth);
  assert.ok(await page.locator('#colBaruCards').evaluate(el=>el.scrollLeft>0));
  await page.locator('#colBaruCards').evaluate(el=>el.scrollLeft=0);
  await page.screenshot({path:path.join(output,'preview-kanban-tablet.png'),fullPage:true});
  await page.setViewportSize({width:1440,height:1050});
  await page.screenshot({path:path.join(output,'preview-kanban-desktop.png'),fullPage:true});
  assert.deepEqual(errors,[]); assert.deepEqual(requests,[]);
  await browser.close();
  console.log('PASS: unpaid order, WA confirmation/status history, POS progression, accounting isolation, paid Dago order, duplicate guard, safe chat text, mobile width, keyboard add, no remote requests or page errors.');
  console.log('Screenshots: '+output);
  console.log('PASS: horizontal intake, three working columns, all drag/drop directions, blocked return to intake, correction notifications, unchanged financials, and accessible status selector.');
})().catch(e=>{console.error(e);process.exit(1)});
